"""Fixed-point vs double-precision comparison report (tracker task 1.7).

Writes results/fixed_vs_double.md. Run: python3 -I python/compare_fixed_vs_double.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import golden as g
import fixed_point as fx
import metrics as m
from grover_ref import grover_program, marked_probability

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results", "fixed_vs_double.md")


def random_program(n, length, seed):
    rng = np.random.default_rng(seed)
    prog = []
    for _ in range(length):
        r = int(rng.integers(6))
        t = int(rng.integers(n))
        if r == 4:
            c = int((t + 1 + rng.integers(n - 1)) % n)
            prog.append(("CNOT", t, c, 0, 0))
        elif r == 5:
            mask = int(rng.integers(1, 1 << n)); prog.append(("MCZ", 0, 0, mask, mask & int(rng.integers(1 << n))))
        else:
            prog.append((["H", "X", "Z", "T"][r], t, 0, 0, 0))
    return prog


def row(label, n, prog, marked=None):
    ref = g.run_program(n, prog)
    fxs = fx.run_program(n, prog)
    tst = fx.to_complex(fxs)
    pm = ""
    if marked is not None:
        pm = f"{marked_probability(ref, marked):.4f} | {marked_probability(tst, marked):.4f}"
    return (f"| {label} | {n} | {len(prog)} | {m.max_amp_error(ref, tst):.2e} | "
            f"{m.fidelity(ref, tst):.8f} | {m.norm_drift(tst):.2e} | {pm or '- | -'} |")


def main():
    rows = []
    for n in (4, 5, 6):
        for L in (20, 100, 400):
            rows.append(row(f"random circuit ({L} gates)", n, random_program(n, L, seed=n * 1000 + L)))
    rows.append(row("Grover, 3 iterations (marked=1010)", 4, grover_program(4, 0b1010, 3), 0b1010))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("# Fixed-point (Q2.14, 16-bit) vs double precision\n\n")
        f.write("Generated by `python/compare_fixed_vs_double.py`. Fixed-point model: round-half-up, saturate, 1/sqrt2 = 0x2D41.\n\n")
        f.write("| Case | Qubits | Gates | Max amp error | Fidelity | Norm drift | P(marked) double | P(marked) fixed |\n")
        f.write("|---|---|---|---|---|---|---|---|\n")
        f.write("\n".join(rows) + "\n")
    print(open(OUT).read())


if __name__ == "__main__":
    main()
